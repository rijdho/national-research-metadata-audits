#!/usr/bin/env node
// The figures the site shows, per country, as one Markdown sheet read from data/<country>/*.json.
// Run it before publishing and compare with the last sheet (git diff NUMBERS.md):
//   node scripts/numbers.mjs > NUMBERS.md
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const read = (c, f) => JSON.parse(readFileSync(join(ROOT, "data", c, f), "utf8"));
const pct = (x) => (x == null ? "n/a" : `${(x * 100).toFixed(1)}%`);
const num = (x) => (x == null ? "n/a" : x.toLocaleString("en"));
const total = (m) => Object.values(m || {}).reduce((a, b) => a + b, 0);
const PERIODS = [["up to 2021", (y) => y <= 2021], ["2022", (y) => y === 2022], ["2023 or later", (y) => y >= 2023]];

const out = ["# Figures shown on the site", "", "Generated by `node scripts/numbers.mjs` from `data/`.", ""];
for (const c of readdirSync(join(ROOT, "data")).sort()) {
  const r = read(c, "repos-overview.json"), t = r.totals;
  const a = read(c, "orcid-overview.json"), s = read(c, "orcid-overview-staff.json");
  const row = (k, v) => out.push(`| ${k} | ${v} |`);
  out.push(`## ${c}`, "", `Repositories generated ${r.generatedAt}; ORCID generated ${a.generatedAt}.`, "", "| Figure | Value |", "|---|---|");
  row("Repositories (with DOIs, measured)", `${num(t.repositories)} (${num(t.withDois)}, ${num(t.measuredRepos)})`);
  row("DOIs", num(t.totalDois));
  row(`Largest repository`, `${r.largest.name}: ${num(r.largest.dois)} DOIs (${pct(r.largest.dois / t.totalDois)})`);
  row("Completeness, mean / DOI-weighted", `${pct(r.avgCompleteness)} / ${pct(r.doiWeightedCompleteness)}`);
  row("Homepage answers (alive + protected) / no URL", `${t.alive} + ${t.protected} of ${t.repositories} / ${t.noUrl}`);
  if (r.fairLive) row("FAIR, 14 criteria on first 10 DOIs", `${pct(r.fairLive.overallPercent / 100)} (${r.fairLive.repos} repositories, ${r.fairLive.metByAll} criteria met by all)`);
  row("FAIR from fields filled, F / A / I / R", ["Findable", "Accessible", "Interoperable", "Reusable"].map((k) => pct(r.fairAverages[k])).join(" / "));
  row("Fields, most to least filled", Object.entries(r.fieldAverages).sort((x, y) => y[1] - x[1]).map(([k, v]) => `${k} ${pct(v)}`).join(", "));
  row("ORCID organisations / distinct profiles / pairs", `${num(a.totalInstitutions)} / ${num(a.uniqueProfiles)} / ${num(a.totalProfiles)}`);
  row("Completeness, all / current staff", `${pct(a.avgOverall)} / ${pct(s.avgOverall)}`);
  row("Without works, all / current staff", `${pct(a.avgEmpty)} / ${pct(s.avgEmpty)}`);
  row("Completeness by link class", Object.entries(a.byLink).map(([k, v]) => `${k} ${pct(v.avgOverall)} (${num(v.profiles)})`).join(", "));
  row("By ROR type (all / staff)", Object.entries(a.byType).map(([k, v]) => `${k}: ${v.count} inst., ${num(v.totalProfiles)} pairs, ${pct(v.avgOverall)} / ${pct(s.byType?.[k]?.avgOverall)}`).join("; "));
  row("Categories, all", Object.entries(a.categoryAverages).map(([k, v]) => `${k} ${pct(v)}`).join(", "));
  row("Checks, all", Object.entries(a.fieldAverages).map(([k, v]) => `${k} ${pct(v)}`).join(", "));
  for (const [label, ov] of [["all", a], ["staff", s]]) {
    const e = ov.employmentIds;
    const by = (keep) => { const m = {}; for (const [y, x] of Object.entries(e.byYear)) if (keep(+y)) for (const [k, v] of Object.entries(x)) m[k] = (m[k] || 0) + v; return m; };
    const share = (m) => pct(total(m) ? (m.ROR || 0) / total(m) : null);
    row(`Employer by ROR, ${label}: overall; ${PERIODS.map(([p]) => p).join("; ")}`,
      `${share(e.elsewhere)} of ${num(total(e.elsewhere))}; ${PERIODS.map(([, keep]) => `${share(by(keep))} of ${num(total(by(keep)))}`).join("; ")}`);
  }
  out.push("");
}
console.log(out.join("\n"));
